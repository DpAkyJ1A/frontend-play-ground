const parse = (rows) =>
  rows.flatMap((row, y) =>
    [...row].flatMap((char, x) => (char === 'O' ? [[x, y]] : []))
  );

export const patterns = {
  gosperGun: parse([
    '........................O...........',
    '......................O.O...........',
    '............OO......OO............OO',
    '...........O...O....OO............OO',
    'OO........O.....O...OO..............',
    'OO........O...O.OO....O.O...........',
    '..........O.....O.......O...........',
    '...........O...O....................',
    '............OO......................',
  ]),
};
